    void previouslyGeneratedBundle() {
        // Optional offline integration input: schemas already generated by the
        // developer. This test never discovers or executes an installed Codex.
        const auto directory = qEnvironmentVariable("DEVHUB_TEST_CODEX_SCHEMA_DIRECTORY");
        if (directory.isEmpty()) QSKIP("No previously generated schema directory supplied.");
        QJsonObject files;
        QDirIterator paths(directory, {"*.json"}, QDir::Files, QDirIterator::Subdirectories);
        while (paths.hasNext()) {
            QFile file(paths.next()); QVERIFY(file.open(QIODevice::ReadOnly));
            QJsonParseError error; const auto document = QJsonDocument::fromJson(file.readAll(), &error);
            QCOMPARE(error.error, QJsonParseError::NoError);
            files.insert(QDir(directory).relativeFilePath(file.fileName()), document.object());
        }
        QElapsedTimer timer; timer.start();
        const auto report = CodexSchemaSurface::inspect(files);
        QVERIFY2(report.protocolCompatible, qPrintable(report.reasonCode() + ": " + report.explanation));
        QVERIFY2(timer.elapsed() < 15000, "Comparing a generated bundle exceeded its processing budget.");
    }
    void generatedStandaloneLayoutUsesSharedDefinitions() {
        const auto snapshot = CodexWireContract("0.162.0-alpha.17.2").snapshot();
        const auto definitions = snapshot.value("definitions");
        QJsonObject files, envelopes;
        const auto contracts = snapshot.value("contracts").toObject();
        for (auto it = contracts.begin(); it != contracts.end(); ++it) {
            const auto kind = it.key().section(':', 0, 0), name = it.key().section(':', 1);
            if (kind == "Response") {
                auto shape = it.value().toObject(); shape.insert("definitions", definitions);
                files.insert("v2/" + name + ".json", shape);
            } else {
                auto variants = envelopes.value(kind).toArray(); variants.append(it.value()); envelopes.insert(kind, variants);
            }
        }
        for (auto it = envelopes.begin(); it != envelopes.end(); ++it)
            files.insert(it.key() + ".json", QJsonObject{{"oneOf", it.value()}, {"definitions", definitions}});
        const auto report = CodexSchemaSurface::inspect(files);
        QVERIFY2(report.protocolCompatible, qPrintable(report.reasonCode()));
    }
