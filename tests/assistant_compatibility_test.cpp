    void behaviorEvidenceBindsEveryRelevantIdentity() {
        CodexCompatibilityReport report;
        report.protocolCompatible = true; report.canonicalExecutable = "C:/fixture/codex.exe";
        report.reportedVersion = "0.163.0-alpha.10.2"; report.binaryIdentity = "measured-binary";
        report.adapter = "paged-resume-v1"; report.schemaIdentity = "measured-schema";
        report.configurationIdentity = "effective-config-and-environment"; report.policyIdentity = "policy-and-tool-inventory";
        const auto key = CodexBehaviorVerifier::evidenceIdentity(report); QVERIFY(!key.isEmpty());
        QCOMPARE(CodexBehaviorVerifier::evidenceIdentity(report), key);
        for (QString CodexCompatibilityReport::* field : {&CodexCompatibilityReport::canonicalExecutable,
            &CodexCompatibilityReport::reportedVersion, &CodexCompatibilityReport::binaryIdentity,
            &CodexCompatibilityReport::adapter, &CodexCompatibilityReport::schemaIdentity,
            &CodexCompatibilityReport::configurationIdentity, &CodexCompatibilityReport::policyIdentity}) {
            auto changed = report; changed.*field += "-changed";
            QVERIFY(CodexBehaviorVerifier::evidenceIdentity(changed) != key);
            changed.*field = {}; QVERIFY(CodexBehaviorVerifier::evidenceIdentity(changed).isEmpty());
        }
        // A value report alone cannot create a saved success or bypass a freshly
        // measured executable, even if an editable flag claims compatibility.
        report.runtimePolicyVerified = true;
        QVERIFY(!CodexBehaviorVerifier::cachedEvidenceMatches(report));
        report.protocolCompatible = false; QVERIFY(CodexBehaviorVerifier::evidenceIdentity(report).isEmpty());
    }
